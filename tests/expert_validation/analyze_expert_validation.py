"""
Praevidio AI — expert validation analysis
==========================================
Compares expert_answers.csv (the expert's 6-year risk in per cent and A/B/C action for each case)
with model_answer_key.json (the v2 and v3 answer key):

  * Action agreement: exact match, linearly weighted Cohen's kappa (ordered A < B < C)
  * Risk agreement:   Spearman rank correlation (expert % against model %), median ratio model / expert
  * Case table:       disagreements are marked

Output: tests/expert_validation/expert_comparison.md
Run:    python tests/expert_validation/analyze_expert_validation.py   (or: make expert-analyze)
"""
import csv
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).parent
ANSWERS = HERE / "expert_answers.csv"
KEY = HERE / "model_answer_key.json"
OUT = HERE / "expert_comparison.md"
ORD = {"A": 0, "B": 1, "C": 2}


def weighted_kappa(a, b, k=3):
    """Linearly weighted Cohen's kappa (ordered categories 0..k-1)."""
    n = len(a)
    if n == 0:
        return float("nan")
    obs = [[0] * k for _ in range(k)]
    for x, y in zip(a, b):
        obs[x][y] += 1
    ra = [sum(obs[i]) / n for i in range(k)]
    rb = [sum(obs[i][j] for i in range(k)) / n for j in range(k)]
    w = [[abs(i - j) / (k - 1) for j in range(k)] for i in range(k)]
    po = sum(w[i][j] * obs[i][j] / n for i in range(k) for j in range(k))
    pe = sum(w[i][j] * ra[i] * rb[j] for i in range(k) for j in range(k))
    return float("nan") if pe == 0 else 1 - po / pe


def _ranks(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(v):
        j = i
        while j + 1 < len(v) and v[order[j + 1]] == v[order[i]]:
            j += 1
        for t in range(i, j + 1):
            r[order[t]] = (i + j) / 2 + 1
        i = j + 1
    return r


def spearman(x, y):
    if len(x) < 3:
        return float("nan")
    rx, ry = _ranks(x), _ranks(y)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = math.sqrt(sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry))
    return float("nan") if den == 0 else num / den


def median(v):
    v = sorted(v)
    n = len(v)
    return float("nan") if n == 0 else (v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2)


def main():
    if not KEY.exists():
        sys.exit("Generate the answer key first: make expert")
    key = {r["id"]: r for r in json.loads(KEY.read_text(encoding="utf-8"))}
    exp = {}
    with open(ANSWERS, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            act = (row.get("expert_action") or "").strip().upper()
            pct = (row.get("expert_risk_6y_pct") or "").strip().replace(",", ".").replace("%", "")
            if act in ORD or pct:
                exp[row["id"].strip()] = {"act": act if act in ORD else None,
                                          "pct": float(pct) if pct else None,
                                          "note": (row.get("note") or "").strip()}
    if not exp:
        sys.exit(f"{ANSWERS.name} is empty; enter the expert's answers (id, expert_risk_6y_pct, expert_action A/B/C, note).")

    ids = [i for i in key if i in exp]
    L = ["# Expert validation: expert against model", "",
         f"*{len(ids)} cases. Generated by `make expert-analyze`; do not edit by hand.*", "",
         "## Summary", "",
         "| Measure | v2 | v3 (6-year layer / full score) |", "| --- | ---: | ---: |"]
    summary = {}
    for m in ("v2", "v3"):
        a_ids = [i for i in ids if exp[i]["act"]]
        ea = [ORD[exp[i]["act"]] for i in a_ids]
        ma = [ORD[key[i][f"{m}_action"]] for i in a_ids]
        exact = sum(x == y for x, y in zip(ea, ma)) / len(a_ids) if a_ids else float("nan")
        within1 = sum(abs(x - y) <= 1 for x, y in zip(ea, ma)) / len(a_ids) if a_ids else float("nan")
        p_ids = [i for i in ids if exp[i]["pct"] is not None]
        ep = [exp[i]["pct"] for i in p_ids]
        cols = [f"{m}_score"] if m == "v2" else ["v3_6y", "v3_score"]
        sp = [spearman(ep, [key[i][c] for i in p_ids]) for c in cols]
        ratio = [median([max(key[i][c], 0.01) / max(exp[i]["pct"], 0.01) for i in p_ids]) for c in cols]
        summary[m] = (exact, within1, weighted_kappa(ea, ma), sp, ratio)
    f2 = lambda x: "–" if x != x else f"{x:.2f}"
    pc = lambda x: "–" if x != x else f"{x*100:.0f} %"
    v2, v3 = summary["v2"], summary["v3"]
    L += [f"| Action, exact agreement | {pc(v2[0])} | {pc(v3[0])} |",
          f"| Action, at most one step apart | {pc(v2[1])} | {pc(v3[1])} |",
          f"| Weighted kappa (action) | {f2(v2[2])} | {f2(v3[2])} |",
          f"| Spearman ρ (risk %) | {f2(v2[3][0])} | {f2(v3[3][0])} / {f2(v3[3][1])} |",
          f"| Median ratio model / expert (risk %) | {f2(v2[4][0])} | {f2(v3[4][0])} / {f2(v3[4][1])} |",
          "",
          "*Reading kappa (Landis and Koch): below 0.20 slight, 0.21–0.40 fair, 0.41–0.60 moderate, 0.61–0.80 "
          "substantial, above 0.80 almost perfect. With ten cases the confidence interval is wide; the results are "
          "indicative only.*",
          "", "## By case", "",
          "A cross marks a case where the model's action differs from the expert's.", "",
          "| # | Expert % | Expert action | v2 % / action | v3 6y % / full % / action | Note |",
          "| --- | ---: | :---: | --- | --- | --- |"]
    for i in ids:
        e, k = exp[i], key[i]
        flag2 = "" if e["act"] in (None, k["v2_action"]) else " ✗"
        flag3 = "" if e["act"] in (None, k["v3_action"]) else " ✗"
        ep = "–" if e["pct"] is None else f"{e['pct']:g}"
        L.append(f"| {i} | {ep} | {e['act'] or '–'} | {k['v2_score']:.1f} / {k['v2_action']}{flag2} | "
                 f"{k['v3_6y']:.1f} / {k['v3_score']:.1f} / {k['v3_action']}{flag3} | {e['note']} |")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[:14]))
    print(f"\nReport: {OUT}")


if __name__ == "__main__":
    main()
