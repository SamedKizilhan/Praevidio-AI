from profiles import ROOT, all_profiles, summarize

OUT = ROOT / "docs" / "model_v3_1_calibration_fix.md"
BASE = json.loads(Path(__file__).with_name("baseline_v3_0.json").read_text(encoding="utf-8"))
LV = {"low": "low", "moderate": "moderate", "high": "high"}

INTRO = """# Risk model v3.1: calibration fix (November 2026)

*The table in section 5 is generated by `make v31-diff`; the tests run with `make model-test`. Edit the narrative in
`tests/model/diff_report.py`, not in this file.*

This note records the fifth finding of the model review: how it was found, its root causes, the fixes and the tests
that now guard them. Two things changed after it was written: the full score is no longer given a band, and a separate
symptom layer with a 3 % threshold was added. Both are described in [`symptom_layer.md`](symptom_layer.md).

## 1. Trigger

In an app trial on 4 November 2026 (a man under 45, 10 cigarettes a day for 10 years, occupational asbestos exposure,
Izmir, no COPD; cough, dyspnoea, chest pain, fatigue and weight loss) v3.0 returned a **6-year risk of 1.49 % (low) and
a score with symptoms of 85.3 % (high)**, with no NICE alert because the person was under 40.
Neither number is clinically defensible. PLCOm2012 gives 0.03–0.10 % for the same person, and in Hamilton et al. 2005
the positive predictive value of a single symptom in primary care, and of every pair that includes cough, is at most
about 2 %.

## 2. Root causes

| # | Problem | Cause | Why it was not caught earlier |
| --- | --- | --- | --- |
| 5a | 6-year risk 2 to 35 times too high for young or light smokers | NLST enrolled only people aged 55–74 with at least 30 pack-years, so the cells "under 55" and "light smoker" returned the cohort level | The comparison set had no young light smoker; the gap between NLST and PLCOm2012 had been measured only on profiles inside the cohort (about 2–3 times) |
| 5b | Risk 4 to 7 times too high for never-smokers | NLST former-smoker cell multiplied by a fixed 0.15 | There was no external reference test for never-smokers |
| 5c | Overconfidence with several symptoms (five symptoms ×380, seven symptoms ×3236) | Chest pain, fatigue, weight loss and haemoptysis were independent of each other in people without cancer; COPD explained only the three respiratory symptoms, and none of them when COPD was denied | It was visible in the table (B2d 99.7 %) but accepted because the decision was "urgent" anyway; there was no test of multi-symptom scores against a clinical target |
| 5d | Haemoptysis with six denials did not raise the risk (×1.0) | The same independence: six denials lowered the probability of symptomatic cancer as much as haemoptysis raised it | The NICE alert caught this case, so the score was not examined |
| 5e | Advice text and PDF tied to the full score | The "high" text told a person with low risk factors that "your risk factors raise your risk"; the PDF still used the v2 texts | Interface texts were not tested |

## 3. Fixes (each behind its own flag; `load_engine("v3.0")` reproduces v3.0 exactly)

**A. 6-year base for ever-smokers from PLCOm2012** (Tammemägi 2013, NEJM 368:728). It uses age, cigarettes per day,
duration and time since quitting as continuous variables. Unknown family history and COPD are averaged over their
priors. Occupational exposure and provincial PM2.5, which PLCOm2012 does not contain, enter as normalised odds-ratio
multipliers (OR / E[OR]). Symptom evidence is carried over from the Bayesian network as a likelihood ratio.

**A2. Base for never-smokers from Wakelee 2007** (J Clin Oncol 25:472; six cohorts, ages 40–79). Age-standardised
incidence is 14.4–20.8 per 100,000 person-years in women and 4.8–13.7 in men. The midpoints are assigned to age 58 and
multiplied by 2.2 per decade; normalised odds ratios are applied for family history, occupational exposure, air
pollution and COPD.

**B. Common-cause node "other illness"** (infection, asthma, reflux, anxiety, musculoskeletal pain and so on),
connected to all seven symptoms by a noisy-OR. The base frequency of every symptom in people without cancer (NHANES and
literature calibration) is preserved exactly (`test_marginal_symptom_prevalence_unchanged_without_cancer`); only the
correlation between symptoms is added. Constraint: p_o ≤ p_cancer, that is, the common cause cannot produce a symptom
more strongly than cancer does. Without this constraint, adding fatigue or wheeze lowered the risk. Calibration: among
5,053 NHANES 2007–12 participants aged 40 or more without cancer, who never smoked and had no diagnosis of COPD,
emphysema or chronic bronchitis, OR(chronic cough, wheeze) = **4.1**. v3.0 assumed **1.0** (independence) in this
group. Under the constraint the closest setting is π = 0.20, ρ = 1.0, which gives **3.4**. The model therefore uses a
slightly weaker correlation than the data and does not overstate the explaining-away effect.

**C. Interface.** The advice text is tied to the 6-year layer and the alert. When symptoms are reported without an
alert, "see your family physician if they have lasted a few weeks" is added. The PDF became two-layered (main figure
the 6-year risk, the score with symptoms on its own row, NICE alert box). Values below 10 % are shown with two
decimals.

## 4. Tests (`tests/model`; 86 tests at the time of the fix, 113 today)

* **Regression.** The v3.0 preset reproduces the frozen output of 43 profiles exactly (`test_baseline.py`).
* **Hamilton envelope.** 127 symptom combinations × 3 base profiles × 3 COPD states. The symptom multiplier is at most
  ×11.3 for a single symptom (×13.6 for haemoptysis), ×11.3 for a pair that includes cough, ×61.6 for any combination
  without haemoptysis and ×113.6 for any combination. v3.0 had 270 violations (the worst 780 times the bound); v3.1
  has none.
* **Information is kept.** Every symptom raises the risk; haemoptysis is the strongest (at least ×3), weight loss and
  chest pain at least ×2, all seven symptoms at least ×10.
* **Consistency.** Adding a symptom does not lower the risk (one exception: wheeze while COPD is unknown, at least
  ×0.8; present since v3.0, an explaining-away effect through COPD). More risk factors, pack-years or age do not lower
  the 6-year risk. Never-smoker ≤ light smoker ≤ heavy smoker.
* **External references.** For ever-smokers the 6-year layer is within 0.5 to 2 times PLCOm2012; for never-smokers it
  is inside the Wakelee range; the NHANES symptom association is inside an odds ratio of 2.5 to 5.5.
* **The trial case.** At ages 30 and 45 the 6-year risk is below 0.5 % and the full score below 10 %; the alert fires
  only at 45.

## 5. Change by profile (v3.0 to v3.1)
"""

OUTRO = """
## 6. Known limitations

* **Symptom association is too weak in smokers.** The model's odds ratio is 1.4 against 3.7 in NHANES. Cough and wheeze
  caused by smoking are not linked to the common cause; the node could later be made to depend on smoking.
* **Wakelee age slope.** The factor of 2.2 per decade rests on the general slope in the literature, not on an
  age-specific table.
* **Scale of the Hamilton figures.** Hamilton's predictive values come from a two-year window in people aged 40 or more
  who consulted primary care. On a six-year horizon they are used as upper bounds; they should be tightened with expert
  opinion and real data.
* **Haemoptysis.** The current value is plausible against Hamilton's figure for haemoptysis at age 70 or more (7.1 %,
  about twice that in smokers) but has not been validated externally.
* **Screening criteria can disagree.** For example S3 (age 60–64, 30 pack-years, quit three years ago) is a screening
  candidate under USPSTF 2021, while the PLCOm2012 risk of 1.37 % is below the 1.51 % threshold. The app shows the two
  separately: a screening-eligibility box and the 6-year risk. This disagreement is known in the literature.
* **Priority of the alert.** The NICE alert is independent of the score and takes priority for the clinical decision;
  the score is for awareness.

## 7. Consequences

* **The expert form (`expert_prediction_form.md`) did not change;** only the model answer key
  (`model_answer_key.md`) was regenerated with v3.1. The v2 and v3.0 values are kept in this document and in
  [`model_comparison_v2_v3.md`](model_comparison_v2_v3.md).
* **Choice of base.** In October the choice between NLST and PLCOm2012 had been left to the expert session. It was
  made here on the strength of the external reference tests and can still be discussed with the expert
  (`load_engine("v3.0")`).
* This is **Finding 5** of the midterm report: detection in a user trial, root cause, a fix calibrated on data, tests.
"""


def main():
    from model.hybrid_bayesian_network_v3 import load_engine
    eng = load_engine("v3.1")
    prof = all_profiles()
    rows, moves6, movesf = [], Counter(), Counter()
    for pid, ev in prof.items():
        a, b = BASE["profiles"][pid], summarize(eng.predict_risk(ev))
        moves6[(LV[a["risk_level_factors"]], LV[b["risk_level_factors"]])] += 1
        movesf[(LV[a["risk_level"]], LV[b["risk_level"]])] += 1
        al = "yes" if b["alarm"] == "urgent" else "–"
        rows.append(f"| {pid} | {a['risk_6y_factors']:.2f} {LV[a['risk_level_factors']]} | "
                    f"**{b['risk_6y_factors']:.2f} {LV[b['risk_level_factors']]}** | "
                    f"{a['risk_score']:.2f} {LV[a['risk_level']]} | **{b['risk_score']:.2f} {LV[b['risk_level']]}** | "
                    f"{b['plcom2012_6y'] if b['plcom2012_6y'] is not None else 'n/a'} | {al} |")
    L = [INTRO,
         "Profile prefixes: S = `scenarios.json`, P = probe cases of the model comparison (Findings 1–4), E = expert "
         "cases. Values are per cent. Bands use the cut-offs in force when the fix was made: low below 1.5 %, moderate "
         "1.5–5 %, high 5 % or more. The same cut-offs were applied to the full score at the time; the full score is no "
         "longer banded. \"NICE alert\" is the NICE NG12 rule under v3.1.", "",
         "| Profile | 6y v3.0 | 6y v3.1 | Full v3.0 | Full v3.1 | PLCOm2012 | NICE alert |",
         "| --- | ---: | ---: | ---: | ---: | ---: | --- |", *rows, "",
         "**Band moves (6-year layer):** " + ", ".join(f"{x} to {y}: {n}" for (x, y), n in sorted(moves6.items())),
         "", "**Band moves (full score):** " + ", ".join(f"{x} to {y}: {n}" for (x, y), n in sorted(movesf.items())),
         OUTRO]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"{len(rows)} profiles -> {OUT}")


if __name__ == "__main__":
    main()
